let _funSpellings = false;

function isFunSpellings() {
  return _funSpellings;
}

function setFunSpellings(on) {
  _funSpellings = !!on;
}

function t(key, vars) {
  const pack = _funSpellings ? I18N.farm : I18N.en;
  let s = pack[key];
  if (s == null) s = I18N.en[key];
  if (s == null) s = key;
  if (vars) {
    Object.keys(vars).forEach(function (k) {
      s = s.split('{' + k + '}').join(String(vars[k]));
    });
  }
  return s;
}

function applyI18n(root) {
  const scope = root || document;
  Array.prototype.forEach.call(scope.querySelectorAll('[data-i18n]'), function (el) {
    const key = el.getAttribute('data-i18n');
    if (!key) return;
    const interval = el.querySelector && el.querySelector('.rating-interval');
    if (interval || el.classList.contains('rating-btn')) {
      const label = el.querySelector('.rating-btn-label, span:not(.rating-interval)');
      if (label) label.textContent = t(key);
      return;
    }
    el.textContent = t(key);
  });
  Array.prototype.forEach.call(scope.querySelectorAll('[data-i18n-placeholder]'), function (el) {
    const key = el.getAttribute('data-i18n-placeholder');
    if (key) el.setAttribute('placeholder', t(key));
  });
  Array.prototype.forEach.call(scope.querySelectorAll('[data-i18n-title]'), function (el) {
    const key = el.getAttribute('data-i18n-title');
    if (key) el.setAttribute('title', t(key));
  });
  Array.prototype.forEach.call(scope.querySelectorAll('[data-i18n-aria]'), function (el) {
    const key = el.getAttribute('data-i18n-aria');
    if (key) el.setAttribute('aria-label', t(key));
  });
  if (document.title !== undefined) document.title = t('appTitle');
}
